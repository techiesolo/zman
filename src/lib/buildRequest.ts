import type {
  Auth,
  Collection,
  FolderItem,
  HttpRequestSpec,
  RequestDef,
  Settings,
  SpecBody,
  SpecFormPart,
} from "../model/types";
import { appendQueryParam, applyPathVars, normalizeUrl } from "./url";
import { resolveVariables, type VarMap } from "./variables";

export const USER_AGENT = "zman/0.1.0";

export interface EffectiveAuth {
  auth: Auth;
  /** Name of the folder or collection the auth was inherited from. */
  inheritedFrom?: string;
}

/** Walks up from the request through its folders to the collection. */
export function effectiveAuth(own: Auth, ancestors: FolderItem[], collection?: Collection): EffectiveAuth {
  if (own.type !== "inherit") return { auth: own };
  for (let i = ancestors.length - 1; i >= 0; i--) {
    const folder = ancestors[i]!;
    if (folder.auth.type !== "inherit") return { auth: folder.auth, inheritedFrom: folder.name };
  }
  if (collection && collection.auth.type !== "inherit") {
    return { auth: collection.auth, inheritedFrom: collection.name };
  }
  return { auth: { type: "none" } };
}

export interface BuildInput {
  request: RequestDef;
  /** Auth after inheritance, see `effectiveAuth`. */
  auth: Auth;
  vars: VarMap;
  settings: Settings;
}

export interface BuildResult {
  spec: HttpRequestSpec;
  warnings: string[];
}

const RAW_CONTENT_TYPES: Record<RequestDef["body"]["rawLanguage"], string> = {
  json: "application/json",
  text: "text/plain",
  xml: "application/xml",
  html: "text/html",
  javascript: "application/javascript",
};

function base64Utf8(text: string): string {
  let binary = "";
  for (const byte of new TextEncoder().encode(text)) binary += String.fromCharCode(byte);
  return btoa(binary);
}

/**
 * Produces the exact request the HTTP engine will send: variables
 * substituted, auth applied, body flattened. The engine itself does no
 * interpretation, so everything Postman-like lives here.
 */
export function buildRequest({ request, auth, vars, settings }: BuildInput): BuildResult {
  const sub = (text: string) => resolveVariables(text, vars);
  const warnings: string[] = [];

  const pathValues: Record<string, string> = {};
  for (const row of request.pathVars) pathValues[row.key] = sub(row.value);
  let url = sub(applyPathVars(request.url, pathValues));

  const headers: [string, string][] = [];
  for (const row of request.headers) {
    if (!row.enabled || row.key.trim() === "") continue;
    headers.push([sub(row.key).trim(), sub(row.value)]);
  }
  const hasHeader = (name: string) => headers.some(([k]) => k.toLowerCase() === name.toLowerCase());
  // A header typed by the user always wins over one zman would add.
  const addDefault = (name: string, value: string) => {
    if (!hasHeader(name)) headers.push([name, value]);
  };

  switch (auth.type) {
    case "basic":
      addDefault("Authorization", `Basic ${base64Utf8(`${sub(auth.username)}:${sub(auth.password)}`)}`);
      break;
    case "bearer":
      addDefault("Authorization", `Bearer ${sub(auth.token)}`);
      break;
    case "apikey": {
      const key = sub(auth.key);
      if (key === "") break;
      if (auth.in === "query") url = appendQueryParam(url, key, sub(auth.value));
      else addDefault(key, sub(auth.value));
      break;
    }
    case "unsupported":
      warnings.push(`"${auth.postmanType}" authorization is not supported and was not applied.`);
      break;
    case "inherit":
    case "none":
      break;
  }

  let body: SpecBody = { kind: "none" };
  const b = request.body;
  switch (b.mode) {
    case "none":
      break;
    case "raw":
      body = { kind: "raw", text: sub(b.raw) };
      addDefault("Content-Type", RAW_CONTENT_TYPES[b.rawLanguage]);
      break;
    case "urlencoded":
      body = {
        kind: "urlencoded",
        fields: b.urlencoded.filter((f) => f.enabled && f.key !== "").map((f) => [sub(f.key), sub(f.value)]),
      };
      break;
    case "formdata": {
      const parts: SpecFormPart[] = [];
      for (const part of b.formdata) {
        if (!part.enabled || part.key === "") continue;
        if (part.type === "file") {
          if (part.value === "") warnings.push(`Form field "${part.key}" has no file selected and was skipped.`);
          else parts.push({ kind: "file", name: sub(part.key), path: part.value });
        } else {
          parts.push({ kind: "text", name: sub(part.key), value: sub(part.value) });
        }
      }
      body = { kind: "formdata", parts };
      // The multipart boundary is generated by the engine; a hand-written
      // Content-Type would not match it.
      for (let i = headers.length - 1; i >= 0; i--) {
        if (headers[i]![0].toLowerCase() === "content-type") headers.splice(i, 1);
      }
      break;
    }
    case "binary":
      if (b.binaryPath === "") warnings.push("No file selected for the binary body; sent without a body.");
      else {
        body = { kind: "binary", path: b.binaryPath };
        addDefault("Content-Type", "application/octet-stream");
      }
      break;
    case "graphql": {
      const payload: { query: string; variables?: unknown } = { query: sub(b.graphqlQuery) };
      const variablesText = sub(b.graphqlVariables).trim();
      if (variablesText !== "") {
        try {
          payload.variables = JSON.parse(variablesText);
        } catch {
          warnings.push("GraphQL variables are not valid JSON and were not sent.");
        }
      }
      body = { kind: "raw", text: JSON.stringify(payload) };
      addDefault("Content-Type", "application/json");
      break;
    }
  }

  addDefault("User-Agent", USER_AGENT);
  addDefault("Accept", "*/*");

  return {
    spec: {
      method: request.method.trim().toUpperCase() || "GET",
      url: normalizeUrl(url),
      headers,
      body,
      options: {
        timeoutMs: settings.timeoutMs,
        followRedirects: settings.followRedirects,
        verifySsl: settings.verifySsl,
        proxy: settings.proxy,
      },
    },
    warnings,
  };
}
